def place_pattern(pattern, size):
    """Places a pattern in the centre of an empty board of the given size."""
    board = np.zeros(size, dtype=np.uint8)
    h, w = pattern.shape
    y = (size[0] - h) // 2
    x = (size[1] - w) // 2
    board[y:y+h, x:x+w] = pattern
    return board